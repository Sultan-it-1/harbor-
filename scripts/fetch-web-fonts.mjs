// Downloads the UI web fonts (Fontshare + Google Fonts) into public/fonts/ and writes
// public/fonts/fonts.css, so the app never waits on a font CDN (the Android app used to
// show a black screen while those stylesheets hung on a captive or slow network).
// Re-run after changing the families below: `node scripts/fetch-web-fonts.mjs`.
import { mkdirSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCES = [
  "https://api.fontshare.com/v2/css?f[]=sentient@400,500,600,700,401,501,601,701&f[]=switzer@400,500,600,700&f[]=general-sans@400,500,600,700&f[]=cabinet-grotesk@400,500,700,800&display=swap",
  "https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,500;9..144,600&family=Inter:wght@400;500;600;700&family=IBM+Plex+Sans:wght@400;500;600;700&family=Plus+Jakarta+Sans:wght@400;500;600;700;800&display=swap",
];
// Google splits each face by script; the UI text is Latin (Arabic uses the system font).
const KEEP_SUBSETS = new Set(["latin", "latin-ext"]);
// A current Chrome UA, so both services answer with woff2.
const UA = "Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Mobile Safari/537.36";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dest = join(root, "public", "fonts");
if (existsSync(dest)) rmSync(dest, { recursive: true });
mkdirSync(dest, { recursive: true });

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const out = [];
const files = new Map();
let total = 0;
for (const src of SOURCES) {
  const res = await fetch(src, { headers: { "user-agent": UA } });
  if (!res.ok) throw new Error(`${res.status} for ${src}`);
  const css = await res.text();
  // Each block is optionally preceded by a "/* subset */" comment (Google).
  const re = /(?:\/\*\s*([a-z-]+)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g;
  for (const m of css.matchAll(re)) {
    const subset = m[1] ?? null;
    if (subset && !KEEP_SUBSETS.has(subset)) continue;
    const body = m[2];
    const family = /font-family:\s*['"]?([^;'"]+)['"]?;/.exec(body)?.[1]?.trim();
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? "400";
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? "normal";
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
    const woff2 = /url\(['"]?([^'")]+\.woff2)['"]?\)/.exec(body)?.[1] ?? /url\(['"]?([^'")]+)['"]?\)\s*format\(['"]woff2['"]\)/.exec(body)?.[1];
    if (!family || !woff2) continue;
    const url = woff2.startsWith("//") ? `https:${woff2}` : woff2;
    // Google serves one variable file for several weights: download it once.
    let file = files.get(url);
    if (!file) {
      file = `${slug(family)}-${slug(weight)}${style === "italic" ? "-italic" : ""}${subset ? `-${subset}` : ""}.woff2`;
      const r = await fetch(url, { headers: { "user-agent": UA } });
      if (!r.ok) throw new Error(`${r.status} for ${url}`);
      const buf = Buffer.from(await r.arrayBuffer());
      writeFileSync(join(dest, file), buf);
      files.set(url, file);
      total += buf.length;
    }
    out.push(
      [
        "@font-face {",
        `  font-family: '${family}';`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        "  font-display: swap;",
        `  src: url('./${file}') format('woff2');`,
        range ? `  unicode-range: ${range};` : null,
        "}",
      ]
        .filter(Boolean)
        .join("\n"),
    );
  }
}
writeFileSync(join(dest, "fonts.css"), `/* Generated by scripts/fetch-web-fonts.mjs. Fontshare (ITF Free Font License) and Google Fonts (SIL OFL). */\n${out.join("\n")}\n`);
console.log(`[web-fonts] ${out.length} faces, ${(total / 1024).toFixed(0)} KB -> public/fonts/`);
