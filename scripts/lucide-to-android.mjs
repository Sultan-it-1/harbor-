// Converts Lucide icons (the icon set the web UI uses) into Android VectorDrawables so
// the native player's buttons match the rest of the app.
//   node scripts/lucide-to-android.mjs
// Writes android/app/src/main/res/drawable/ic_<name>.xml (white stroke; tint in code).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ICON_DIR = join(root, "node_modules/lucide-react/dist/esm/icons");
const OUT = join(root, "android/app/src/main/res/drawable");

const ICONS = [
  "x", "captions", "audio-lines", "layers", "lock", "lock-open", "scan", "sun", "volume-2",
  "volume-x", "rewind", "fast-forward", "skip-forward", "gauge", "check", "refresh-cw", "type",
  "arrow-left", "languages", "chevron-right", "play", "pause", "download", "plus", "users", "pencil", "arrow-up", "arrow-down", "eye", "eye-off", "list-ordered", "sparkles", "trash-2", "rotate-ccw", "quote", "external-link", "chevron-left", "search", "chevron-down", "tag", "calendar", "clock", "globe", "building-2", "tv", "ellipsis", "shuffle", "info", "bookmark", "bookmark-check", "thumbs-down", "rotate-cw", "wifi", "battery-charging", "magnet", "link-2", "circle-alert", "star", "list-checks", "list-plus", "zap", "radio", "crown", "copy", "arrow-right", "settings-2", "grip-vertical", "archive-restore", "history", "trending-up", "library", "link", "chevrons-up", "arrow-up-down",
];

const n = (v) => Number(v);
const fmt = (v) => String(Math.round(v * 1000) / 1000);

function rectPath({ x = 0, y = 0, width, height, rx, ry }) {
  x = n(x); y = n(y); const w = n(width); const h = n(height);
  let rX = rx != null ? n(rx) : ry != null ? n(ry) : 0;
  let rY = ry != null ? n(ry) : rX;
  rX = Math.min(rX, w / 2); rY = Math.min(rY, h / 2);
  if (!rX) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}z`;
  return [
    `M${fmt(x + rX)} ${fmt(y)}`, `h${fmt(w - 2 * rX)}`, `a${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(rX)} ${fmt(rY)}`,
    `v${fmt(h - 2 * rY)}`, `a${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(-rX)} ${fmt(rY)}`, `h${fmt(-(w - 2 * rX))}`,
    `a${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(-rX)} ${fmt(-rY)}`, `v${fmt(-(h - 2 * rY))}`,
    `a${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(rX)} ${fmt(-rY)}`, "z",
  ].join("");
}
const ellipsePath = (cx, cy, rx, ry) =>
  `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0z`;
const pointsPath = (pts, close) => {
  const p = pts.trim().split(/[\s,]+/).map(n);
  let d = `M${fmt(p[0])} ${fmt(p[1])}`;
  for (let i = 2; i < p.length; i += 2) d += `L${fmt(p[i])} ${fmt(p[i + 1])}`;
  return close ? d + "z" : d;
};

function toPath([tag, a]) {
  switch (tag) {
    case "path": return a.d;
    case "rect": return rectPath(a);
    case "circle": return ellipsePath(n(a.cx), n(a.cy), n(a.r), n(a.r));
    case "ellipse": return ellipsePath(n(a.cx), n(a.cy), n(a.rx), n(a.ry));
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": return pointsPath(a.points, false);
    case "polygon": return pointsPath(a.points, true);
    default: throw new Error(`unsupported element ${tag}`);
  }
}

function nodesOf(name) {
  const src = readFileSync(join(ICON_DIR, `${name}.js`), "utf8");
  const m = src.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/);
  if (!m) throw new Error(`cannot read ${name}`);
  // The node list is a plain JSON-like literal of [tag, {attrs}] pairs.
  return JSON.parse(m[1].replace(/(\w+):/g, '"$1":').replace(/,\s*key:\s*"[^"]*"/g, ""));
}

mkdirSync(OUT, { recursive: true });
for (const name of ICONS) {
  const paths = nodesOf(name).map(toPath);
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Lucide "${name}" (ISC licence), generated by scripts/lucide-to-android.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
${paths.map((d) => `    <path android:pathData="${d}" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"
        android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />`).join("\n")}
</vector>
`;
  writeFileSync(join(OUT, `ic_${name.replace(/-/g, "_")}.xml`), xml);
}
console.log(`wrote ${ICONS.length} icons to ${OUT}`);
