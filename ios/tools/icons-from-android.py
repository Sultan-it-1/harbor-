#!/usr/bin/env python3
"""Writes ios/native/App/App/Native/IconPaths.swift from Android's vector icons
(android/app/src/main/res/drawable/ic_*.xml, Lucide outlines): the same icons on both."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
src = root / "android/app/src/main/res/drawable"
out = root / "ios/native/App/App/Native/IconPaths.swift"

entries = []
for f in sorted(src.glob("ic_*.xml")):
    paths = re.findall(r'android:pathData="([^"]+)"', f.read_text())
    if not paths:
        continue
    name = f.stem[3:]
    body = ", ".join('"' + p.replace("\\", "\\\\").replace('"', '\\"') + '"' for p in paths)
    entries.append(f'        "{name}": [{body}],')

out.write_text(
    "// Generated by ios/tools/icons-from-android.py from android/app/src/main/res/drawable\n"
    "// (Lucide icons, ISC licence): the same icons as the Android app. Do not edit by hand.\n\n"
    "enum IconPaths {\n"
    "    /// Each icon's SVG path data, on a 24 x 24 grid, drawn with a 2-unit round stroke.\n"
    "    static let all: [String: [String]] = [\n"
    + "\n".join(entries)
    + "\n    ]\n}\n"
)
print(f"{len(entries)} icons -> {out.relative_to(root)}")
